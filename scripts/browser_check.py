"""Exercise the actual Chrome extension with local, synthetic Web Audio."""
import json
import base64
from pathlib import Path
import subprocess
from tempfile import TemporaryDirectory
from time import monotonic, sleep
from urllib.request import urlopen

from playwright.sync_api import sync_playwright
from websockets.sync.client import connect

from studio.capture import Capture
from studio.store import Store

MEET_URL = "https://meet.google.com/abc-defg-hij"
SYNTHETIC_TAB = """
<title>Local Meet audio fixture</title><button>Play a test tone</button>
<script>
const context = new AudioContext();
window.pitch = 440;
document.querySelector('button').onclick = async () => {
  const tone = context.createOscillator();
  const volume = context.createGain();
  volume.gain.value = 0.15;
  tone.frequency.value = window.pitch;
  tone.connect(volume).connect(context.destination);
  await context.resume();
  tone.start();
  window.generator = tone;
};
window.playSpeech = async (encoded) => {
  window.generator.stop();
  const wave = await context.decodeAudioData(Uint8Array.from(atob(encoded), ch => ch.charCodeAt(0)).buffer);
  const voice = context.createBufferSource();
  voice.buffer = wave;
  voice.connect(context.destination);
  voice.start();
};
</script>
"""


class QuietRecognizer:
    def decode(self, audio):
        return []


def wait_for(predicate, timeout=7):
    deadline = monotonic() + timeout
    while monotonic() < deadline:
        result = predicate()
        if result:
            return result
        sleep(.05)
    raise AssertionError("Timed out waiting for the next browser test state.")


def js(socket, expression, identifier=1):
    socket.send(json.dumps({"id": identifier, "method": "Runtime.evaluate",
                            "params": {"expression": expression, "returnByValue": True}}))
    while True:
        result = json.loads(socket.recv(timeout=5))
        if result.get("id") == identifier:
            if "error" in result or result.get("result", {}).get("exceptionDetails"):
                raise RuntimeError(str(result))
            return result["result"]["result"].get("value")


def main():
    from argparse import ArgumentParser
    parser = ArgumentParser()
    parser.add_argument("chrome", type=Path)
    parser.add_argument("--voice", type=Path, help="Windows SAPI beginner.wav generated by synthetic.ps1.")
    parser.add_argument("--cache", type=Path, default=Path("private/models"))
    args = parser.parse_args()
    extension = Path(__file__).resolve().parent.parent / "extension"
    with TemporaryDirectory(ignore_cleanup_errors=True) as folder:
        store = Store(Path(folder) / "sessions.sqlite")
        profile = Path(folder) / "chrome"
        profile.mkdir()
        capture = Capture(store)
        capture.recognizer = QuietRecognizer()
        capture.mic = "Synthetic test source"
        capture.select_meeting("abc-defg-hij")
        capture.server_start()
        lesson = store.create({"student_id": "fixture", "name": "Fictional", "level": "B1"}, True)
        sample = store.sample(lesson, "Unlabelled")
        options = [str(args.chrome), "--headless=new", "--no-first-run", "--disable-background-networking",
                   "--no-default-browser-check", "--remote-debugging-port=0", f"--user-data-dir={profile}",
                   f"--disable-extensions-except={extension}", f"--load-extension={extension}",
                   "--enable-unsafe-extension-debugging", "about:blank"]
        chrome = subprocess.Popen(options, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        try:
            with sync_playwright() as playwright:
                port_file = profile / "DevToolsActivePort"
                wait_for(port_file.exists)
                endpoint = "http://127.0.0.1:" + port_file.read_text().splitlines()[0]
                browser = playwright.chromium.connect_over_cdp(endpoint)
                context = browser.contexts[0]
                context.route("https://meet.google.com/**", lambda route: route.fulfill(content_type="text/html",
                                                                                        body=SYNTHETIC_TAB))
                context.route("https://outside.test/**", lambda route: route.fulfill(body="Outside the meeting"))
                tab = context.new_page()
                tab.goto(MEET_URL)
                tab.get_by_role("button", name="Play a test tone").click()
                unrelated = context.new_page()
                unrelated.goto("https://meet.google.com/xxx-yyyy-zzz")
                unrelated.evaluate("window.pitch = 997")
                unrelated.get_by_role("button").click()
                tab.bring_to_front()
                cdp = browser.new_browser_cdp_session()
                info = cdp.send("Target.getTargets")["targetInfos"]
                worker = next((target for target in info if target["url"].endswith("/worker.js")
                               and target["url"].startswith("chrome-extension://")), None)
                if not worker:
                    try:
                        extension_id = cdp.send("Extensions.loadUnpacked", {"path": str(extension)})["id"]
                    except Exception as e:
                        raise RuntimeError("Use a recent Chromium or Chrome for Testing build with extension development support.") from e
                else:
                    extension_id = worker["url"].split("/")[2]
                tabs = cdp.send("Target.getTargets", {"filter": [{"type": "tab"}, {"exclude": True}]})["targetInfos"]
                target = next(item["targetId"] for item in tabs if item["url"] == MEET_URL)
                cdp.send("Extensions.triggerAction", {"id": extension_id, "targetId": target})

                def popup_socket():
                    with urlopen(endpoint + "/json/list", timeout=4) as response:
                        targets = json.load(response)
                    return next((item["webSocketDebuggerUrl"] for item in targets
                                 if item["url"] == f"chrome-extension://{extension_id}/popup.html"), None)

                with connect(wait_for(popup_socket)) as popup:
                    js(popup, f"document.querySelector('#code').value = {json.dumps(capture.token)}; "
                              "document.querySelector('form').requestSubmit(); true")
                    wait_for(lambda: capture.snapshot()["tab"])
                    assert capture.snapshot()["student"] == 0
                    capture.start(sample, "assessment")
                    wait_for(lambda: capture.snapshot()["student"] > .05)
                    # Inspect a transient recording buffer before the fake recognizer drops it.
                    with capture.lock:
                        import numpy as np
                        block = np.concatenate(capture.buffers["student"].chunks)
                        spectrum = abs(np.fft.rfft(block))
                        hz = float(np.fft.rfftfreq(len(block), 1 / 16000)[spectrum.argmax()])
                        assert abs(hz - 440) < 12, hz
                    capture.pause()
                    wait_for(lambda: capture.snapshot()["pending"] == 0)
                    revision = capture.snapshot()["revision"]
                    with capture.lock:
                        assert not capture.buffers["student"].chunks
                    sleep(.3)
                    assert capture.snapshot()["revision"] == revision and capture.snapshot()["student"] == 0
                    capture.start(sample, "transcript")
                    wait_for(lambda: capture.snapshot()["student"] > .05)
                tab.close()
                wait_for(lambda: capture.snapshot()["mode"] == "paused")
                assert not capture.snapshot()["tab"]
                print(f"Real tabCapture and AudioWorklet passed. Dominant frequency {hz:.1f} Hz. "
                      "A 997 Hz tone in another tab was excluded. Pause, resume and tab closure passed.")
                if args.voice:
                    from studio.analysis import tokens
                    from studio.asr import Recognizer
                    capture.recognizer = Recognizer("base.en", "cpu", str(args.cache), download=False)
                    tab = context.new_page()
                    tab.goto(MEET_URL)
                    tab.get_by_role("button").click()
                    tabs = cdp.send("Target.getTargets", {"filter": [{"type": "tab"}, {"exclude": True}]})["targetInfos"]
                    target = next(item["targetId"] for item in tabs if item["url"] == MEET_URL)
                    cdp.send("Extensions.triggerAction", {"id": extension_id, "targetId": target})
                    with connect(wait_for(popup_socket)) as popup:
                        js(popup, f"document.querySelector('#code').value = {json.dumps(capture.token)}; "
                                  "document.querySelector('form').requestSubmit(); true")
                        wait_for(lambda: capture.snapshot()["tab"])
                        capture.start(sample, "assessment")
                        wait_for(lambda: capture.snapshot()["student"] > .05)
                        before = capture.snapshot()["revision"]
                        tab.evaluate("encoded => window.playSpeech(encoded)",
                                     base64.b64encode(args.voice.read_bytes()).decode())
                        wait_for(lambda: capture.snapshot()["revision"] > before, timeout=12)
                        capture.pause()
                        turns = store.load(lesson)["samples"][0]["turns"]
                        assert any(turn["speaker"] == "student" and not turn["flags"]
                                   and tokens(turn["text"]) == ["yes", "i", "can"] for turn in turns), turns
                    capture.start(sample, "assessment")
                    tab.goto("https://outside.test/after-meet")
                    wait_for(lambda: not capture.snapshot()["tab"] and capture.snapshot()["mode"] == "paused")
                    print("Synthetic spoken answer reached the SQLite transcript through real tabCapture and CPU Whisper.")
        finally:
            capture.close()
            chrome.terminate()
            chrome.wait(timeout=10)


if __name__ == "__main__":
    main()
